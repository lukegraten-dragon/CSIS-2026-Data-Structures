#include <iostream>

using namespace std ;
 
int main()   
{  
    int a, b ;
    double z ;
    char ch ;

    cin >> ch ;
    cout << "ch = " << ch << endl ;
    
    cin >> a ;
    cout << "a = " << a << endl ;

    cin >> z ;
    cout << "z = " << z << endl ;

    cin >> a >> b ;
    cout << "a = " << a << endl << "b = " << b << endl ;
    
    return 0 ;
}